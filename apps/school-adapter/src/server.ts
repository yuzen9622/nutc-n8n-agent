import {createServer} from 'node:http';
import {Pool} from 'pg';
import {loadSchoolConfig} from './config/env.js';
import {assertRuntimeKey} from '../../shared/runtime-key-guard.mjs';
import {SessionCrypto} from './modules/school/session.crypto.js';
import {SchoolSessionRepository} from './modules/school/session.repository.js';
import {SchoolLoginService} from './modules/school/login.service.js';
import {LocalOcr} from './modules/school/ocr.provider.js';
import {SchoolService} from './modules/school/school.service.js';
import {LeaveCrypto} from './modules/school/leave.crypto.js';
import {LeaveRepository} from './modules/school/leave.repository.js';
import {LeaveService} from './modules/school/leave.service.js';
import {SchoolController} from './modules/school/school.controller.js';
import {schoolRouter} from './modules/school/school.router.js';
const config=loadSchoolConfig();
const pool=new Pool({connectionString:config.SCHOOL_DATABASE_URL,max:5,connectionTimeoutMillis:3000,statement_timeout:5000});
pool.on('error',()=>console.error('School database unavailable'));
await assertRuntimeKey(pool,process.env.APP_MASTER_KEY).catch(async error=>{await pool.end();throw error;});
const sessions=new SchoolSessionRepository(pool,new SessionCrypto(config.SCHOOL_SESSION_KEY,config.SCHOOL_ACCOUNT_HASH_KEY));
const ocr=new LocalOcr(),service=new SchoolService(sessions,new SchoolLoginService((image,signal)=>ocr.recognize(image,signal)));
const leaves=new LeaveRepository(pool,new LeaveCrypto(config.SCHOOL_SESSION_KEY));
const server=createServer(schoolRouter(new SchoolController(service,new LeaveService(leaves,sessions)),config.SCHOOL_SERVICE_TOKEN));
server.requestTimeout=45000;server.headersTimeout=10000;
const cleanup=setInterval(()=>void Promise.all([sessions.cleanup(),leaves.cleanup()]).catch(()=>console.error('School session cleanup unavailable')),60000);cleanup.unref();
server.listen(config.SCHOOL_PORT,config.SCHOOL_HOST,()=>console.log('School adapter ready'));
for(const signal of ['SIGTERM','SIGINT'])process.once(signal,()=>{clearInterval(cleanup);server.close(()=>void pool.end());});
